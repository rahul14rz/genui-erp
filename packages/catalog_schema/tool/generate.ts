import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { dartModels } from "./dart.ts";
import { BINDING, loadCatalog, modelSchema, stripAnnotations, type Catalog, type JsonSchema } from "./schema.ts";
import { zodOf } from "./zod.ts";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const SCHEMA_DIR = join(ROOT, "packages", "catalog_schema");
const ROLES = ["owner", "sales_rep", "warehouse", "accounts"] as const;
const HEADER = "// Generated by packages/catalog_schema/tool/generate.ts. Do not edit.\n";

type PermissionsFile = {
  permissions: Record<string, string>;
  roles: Record<string, string[]>;
};

function loadPermissions(): PermissionsFile {
  const file = JSON.parse(readFileSync(join(SCHEMA_DIR, "permissions.json"), "utf8")) as PermissionsFile;
  const known = new Set(Object.keys(file.permissions));
  const roles = Object.keys(file.roles).sort();
  if (roles.join() !== [...ROLES].sort().join()) {
    throw new Error(`permissions.json roles must be exactly ${ROLES.join(", ")}`);
  }
  for (const [role, grants] of Object.entries(file.roles)) {
    for (const g of grants) if (!known.has(g)) throw new Error(`${role} grants unknown permission ${g}`);
  }
  return file;
}

function permissionsTs(p: PermissionsFile): string {
  const names = Object.keys(p.permissions);
  return `${HEADER}
export const PERMISSIONS = ${JSON.stringify(names, null, 2)} as const;
export type Permission = (typeof PERMISSIONS)[number];

export const ROLE_PERMISSIONS = {
${ROLES.map((r) => `  ${r}: ${JSON.stringify(p.roles[r])},`).join("\n")}
} as const satisfies Record<string, readonly Permission[]>;

export const PERMISSION_DESCRIPTIONS: Record<Permission, string> = ${JSON.stringify(p.permissions, null, 2)};
`;
}

function sortedDefs(defs: Record<string, JsonSchema>): string[] {
  const refs = (s: unknown): string[] =>
    s && typeof s === "object"
      ? Object.entries(s).flatMap(([k, v]) => (k === "$ref" && typeof v === "string" ? [v.replace("#/$defs/", "")] : refs(v)))
      : [];
  const out: string[] = [];
  const visit = (name: string) => {
    if (out.includes(name)) return;
    for (const r of refs(defs[name])) if (r !== name) visit(r);
    out.push(name);
  };
  Object.keys(defs).forEach(visit);
  return out;
}

function catalogTs(catalog: Catalog): string {
  const defs = { ...catalog.defs, Binding: BINDING };
  const defLines = sortedDefs(defs).map((name) => `export const ${name} = ${zodOf(defs[name]!)};`);
  const wire = catalog.components.map((c) => `  ${c.name}: ${zodOf(c.schema)},`);
  const model = catalog.components.filter((c) => !c.serverOnly).map((c) => `  ${c.name}: ${zodOf(modelSchema(c.schema))},`);
  const meta = catalog.components.map((c) => ({
    name: c.name,
    description: c.description,
    permission: c.permission,
    serverOnly: c.serverOnly,
  }));
  const modelJson = Object.fromEntries(
    catalog.components.filter((c) => !c.serverOnly).map((c) => [c.name, stripAnnotations(modelSchema(c.schema))]),
  );
  const rawJson = Object.fromEntries(catalog.components.map((c) => [c.name, c.schema]));
  return `${HEADER}
import { z } from "zod";

${defLines.join("\n")}

/** The shape each component has on the wire, after the server resolves bindings. */
export const WIRE = {
${wire.join("\n")}
} as const;

/** The shape the model writes. Bindable properties also accept {"bind": "..."}. */
export const MODEL = {
${model.join("\n")}
} as const;

export type ComponentName = keyof typeof WIRE;

export const COMPONENTS: readonly { name: ComponentName; description: string; permission: string | null; serverOnly: boolean }[] = ${JSON.stringify(meta, null, 2)};

/** JSON Schema for each model-writable component, used to describe the catalog to the model. */
export const MODEL_JSON_SCHEMAS: Record<string, unknown> = ${JSON.stringify(modelJson, null, 2)};

export const DEFS_JSON_SCHEMA: Record<string, unknown> = ${JSON.stringify(stripAnnotations(defs), null, 2)};

/** The source schemas with their x- annotations, for walking field, action and child references. */
export const ANNOTATED_SCHEMAS: Record<string, unknown> = ${JSON.stringify(rawJson, null, 2)};

export const ANNOTATED_DEFS: Record<string, unknown> = ${JSON.stringify(catalog.defs, null, 2)};
`;
}

function permissionsMd(p: PermissionsFile, catalog: Catalog): string {
  const roles = [...ROLES];
  const yes = (r: string, perm: string) => (p.roles[r]!.includes(perm) ? "yes" : "");
  const permRows = Object.entries(p.permissions)
    .map(([perm, desc]) => `| \`${perm}\` | ${desc} | ${roles.map((r) => yes(r, perm)).join(" | ")} |`)
    .join("\n");
  const compRows = catalog.components
    .map((c) => {
      const who =
        c.permission === null
          ? roles.map(() => "yes")
          : c.permission === "@action"
            ? roles.map((r) => (p.roles[r]!.some((g) => /:(decide|adjust|create|request|mark|record)$/.test(g)) ? "yes" : ""))
            : roles.map((r) => yes(r, c.permission!));
      const req = c.permission === null ? "any signed-in user" : c.permission === "@action" ? "any action permission" : `\`${c.permission}\``;
      return `| ${c.name} | ${req}${c.serverOnly ? ", server only" : ""} | ${who.join(" | ")} |`;
    })
    .join("\n");
  return `<!-- Generated by packages/catalog_schema/tool/generate.ts from permissions.json and the component schemas. Do not edit. -->

# Permissions

Every check below runs on the server. The client only draws what the server sent.

## The three layers

1. **Data.** The server logs in to Postgres as \`genui_app\`, which owns nothing and has no table privileges. Each request runs in one transaction that switches to the role's own Postgres role (\`genui_role_owner\`, \`genui_role_sales_rep\`, \`genui_role_warehouse\`, \`genui_role_accounts\`) and sets \`app.tenant_id\`, \`app.user_id\` and \`app.user_role\`. A restrictive RLS policy on every table limits rows to the tenant. Permissive policies per role narrow further, for example a sales rep sees only customers they own and those customers' orders. Column grants hide cost, price, margin and credit limit columns from roles that must not see them, because RLS filters rows, not columns. See \`db/migrations/0001_rls.sql\`.
2. **Tools.** Each tool declares one permission. The model is only told about tools the role holds, and a call to any other tool gets the same "not available" answer whether it exists or not. Fields such as order value or margin are added to a tool's output only when the role holds \`prices:read\` or \`margin:read\`, and the database would refuse the column anyway.
3. **UI.** Each catalog component declares a permission (table below). The server builds the role's catalog per session, validates every model answer against it, and checks every outgoing A2UI message again before it is written. Actions referenced by a component must be actions the role holds. User actions come back to server handlers that check the permission again, require an idempotency key, run in one transaction and write the audit row in it.

## Permissions by role

| Permission | Meaning | ${roles.join(" | ")} |
|---|---|${roles.map(() => "---").join("|")}|
${permRows}

## Components by role

| Component | Requires | ${roles.join(" | ")} |
|---|---|${roles.map(() => "---").join("|")}|
${compRows}
`;
}

type Output = { path: string; content: string };

export function outputs(): Output[] {
  const permissions = loadPermissions();
  const catalog = loadCatalog(join(SCHEMA_DIR, "components"), new Set(Object.keys(permissions.permissions)));
  return [
    { path: join(ROOT, "apps/server/src/generated/permissions.ts"), content: permissionsTs(permissions) },
    { path: join(ROOT, "apps/server/src/generated/catalog.ts"), content: catalogTs(catalog) },
    { path: join(ROOT, "packages/erp_design/lib/src/catalog/generated.dart"), content: dartModels(catalog) },
    { path: join(ROOT, "docs/permissions.md"), content: permissionsMd(permissions, catalog) },
  ];
}

const check = process.argv.includes("--check");
let drift = 0;
for (const out of outputs()) {
  const rel = relative(ROOT, out.path);
  const current = existsSync(out.path) ? readFileSync(out.path, "utf8") : null;
  if (current === out.content) continue;
  if (check) {
    console.error(`out of date: ${rel}`);
    drift++;
  } else {
    mkdirSync(dirname(out.path), { recursive: true });
    writeFileSync(out.path, out.content);
    console.log(`wrote ${rel}`);
  }
}
if (check && drift) {
  console.error("run `pnpm --filter @genui-erp/catalog-schema generate` and commit the result");
  process.exit(1);
}
if (check) console.log("generated files are up to date");
