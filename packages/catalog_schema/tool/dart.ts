import type { Catalog, JsonSchema } from "./schema.ts";
import { stripAnnotations } from "./schema.ts";

const cap = (s: string) => s[0]!.toUpperCase() + s.slice(1);
const singular = (s: string) => (s === "series" || !s.endsWith("s") ? s : s.slice(0, -1));

/** Emits immutable Dart model classes with fromJson for the wire shape of each component. */
export function dartModels(catalog: Catalog): string {
  const classes: string[] = [];
  const enums = new Map<string, string[]>();
  const emitted = new Set<string>();

  const typeOf = (s: JsonSchema, name: string): string => {
    if (s.$ref) {
      const ref = s.$ref.replace("#/$defs/", "");
      const def = catalog.defs[ref]!;
      if (def.type === "object" && !def.properties) return "Map<String, Object?>";
      return typeOf(def, ref);
    }
    if (s.enum) {
      enums.set(name, s.enum);
      return name;
    }
    if (Array.isArray(s.type)) return "Object";
    switch (s.type) {
      case "string":
        return "String";
      case "number":
        return "num";
      case "integer":
        return "int";
      case "boolean":
        return "bool";
      case "array":
        return `List<${typeOf(s.items ?? {}, name)}>`;
      case "object":
        if (!s.properties) return "Map<String, Object?>";
        emitClass(name, s);
        return name;
      default:
        return "Object";
    }
  };

  const read = (s: JsonSchema, expr: string, name: string): string => {
    const t = typeOf(s, name);
    if (t === "String" || t === "bool" || t === "int") return `${expr} as ${t}`;
    if (t === "num") return `${expr} as num`;
    if (t === "Object") return expr;
    if (t === "Map<String, Object?>") return `Map<String, Object?>.from(${expr} as Map)`;
    if (enums.has(t)) return `${t}.fromJson(${expr} as String)`;
    if (t.startsWith("List<")) {
      const itemSchema = s.$ref ? catalog.defs[s.$ref.replace("#/$defs/", "")]!.items! : s.items!;
      return `[for (final e in ${expr} as List) ${read(itemSchema, "e", name)}]`;
    }
    return `${t}.fromJson(Map<String, Object?>.from(${expr} as Map))`;
  };

  function emitClass(name: string, s: JsonSchema) {
    if (emitted.has(name)) return;
    emitted.add(name);
    const required = new Set(s.required ?? []);
    const props = Object.entries(s.properties ?? {}).map(([k, v]) => {
      const childName = v.$ref ? v.$ref.replace("#/$defs/", "") : `${name}${cap(singular(k))}`;
      const t = typeOf(v, childName);
      const nullable = !required.has(k) || t === "Object";
      const decl = nullable && t !== "Object" ? `${t}?` : t === "Object" ? "Object?" : t;
      const access = `json['${k}']`;
      const value = nullable && t !== "Object" ? `${access} == null ? null : ${read(v, access, childName)}` : read(v, access, childName);
      return { k, decl, nullable, value };
    });
    classes.push(`@immutable
final class ${name} {
  const ${name}({${props.map((p) => `${p.nullable ? "" : "required "}this.${p.k}`).join(", ")}});

  factory ${name}.fromJson(Map<String, Object?> json) => ${name}(
${props.map((p) => `        ${p.k}: ${p.value},`).join("\n")}
      );

${props.map((p) => `  final ${p.decl} ${p.k};`).join("\n")}
}
`);
  }

  for (const c of catalog.components) emitClass(c.name, c.schema);

  const enumSrc = [...enums.entries()].map(
    ([name, values]) => `enum ${name} {
${values.map((v) => `  ${v}('${v}'),`).join("\n")};

  const ${name}(this.json);
  final String json;

  static ${name} fromJson(String value) =>
      values.firstWhere((e) => e.json == value, orElse: () => throw FormatException('Unknown ${name}: \$value'));
}
`,
  );

  const schemas = catalog.components
    .map((c) => `  '${c.name}': r'''${JSON.stringify(inlineDefs(c.schema, catalog))}''',`)
    .join("\n");
  const permissions = catalog.components.map((c) => `  '${c.name}': ${c.permission === null ? "null" : `'${c.permission}'`},`).join("\n");

  return `// Generated by packages/catalog_schema/tool/generate.ts. Do not edit.
// ignore_for_file: prefer_single_quotes, lines_longer_than_80_chars

import 'package:flutter/foundation.dart';

${enumSrc.join("\n")}
${classes.join("\n")}
/// JSON Schema of each component's wire shape, with shared definitions inlined.
const Map<String, String> catalogSchemas = {
${schemas}
};

/// The permission each component requires. Null means any signed-in user.
const Map<String, String?> componentPermissions = {
${permissions}
};
`;
}

function inlineDefs(s: JsonSchema, catalog: Catalog): unknown {
  const walk = (node: unknown): unknown => {
    if (Array.isArray(node)) return node.map(walk);
    if (node && typeof node === "object") {
      const n = node as JsonSchema;
      if (n.$ref) return walk(catalog.defs[n.$ref.replace("#/$defs/", "")]);
      return Object.fromEntries(Object.entries(n).map(([k, v]) => [k, walk(v)]));
    }
    return node;
  };
  return stripAnnotations(walk(s));
}
